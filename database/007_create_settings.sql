CREATE TABLE IF NOT EXISTS staff_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    full_name VARCHAR(150),
    email VARCHAR(254),
    phone VARCHAR(30),
    designation VARCHAR(100),
    role VARCHAR(40) NOT NULL DEFAULT 'STAFF',
    photo_url VARCHAR(500),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS facility_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    facility_name VARCHAR(200),
    mfl_code VARCHAR(30),
    county VARCHAR(100),
    sub_county VARCHAR(100),
    location VARCHAR(200),
    contact_phone VARCHAR(30),
    contact_email VARCHAR(254),
    administrator_name VARCHAR(150),
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_preferences (
    username VARCHAR(100) PRIMARY KEY,
    theme VARCHAR(20) NOT NULL DEFAULT 'light',
    text_size VARCHAR(20) NOT NULL DEFAULT 'normal',
    language VARCHAR(20) NOT NULL DEFAULT 'en',
    anc_reminders BOOLEAN NOT NULL DEFAULT TRUE,
    immunization_reminders BOOLEAN NOT NULL DEFAULT TRUE,
    pnc_reminders BOOLEAN NOT NULL DEFAULT TRUE,
    missed_appointment_notifications BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL,
    record_reference VARCHAR(200),
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS audit_logs_occurred_at_idx ON audit_logs (occurred_at DESC);
CREATE INDEX IF NOT EXISTS audit_logs_username_idx ON audit_logs (username);

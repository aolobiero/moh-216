CREATE TABLE IF NOT EXISTS pnc_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mother_id BIGINT NOT NULL REFERENCES mothers(id),
    visit_date DATE NOT NULL,
    delivery_recovery_notes VARCHAR(4000),
    systolic_bp INTEGER,
    diastolic_bp INTEGER,
    breastfeeding_support VARCHAR(2000),
    maternal_wellbeing_notes VARCHAR(2000),
    complications VARCHAR(2000),
    family_planning_counselling VARCHAR(2000),
    referral_notes VARCHAR(2000),
    next_visit_date DATE,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pnc_systolic_positive CHECK (systolic_bp IS NULL OR systolic_bp > 0),
    CONSTRAINT pnc_diastolic_positive CHECK (diastolic_bp IS NULL OR diastolic_bp > 0)
);

CREATE INDEX IF NOT EXISTS pnc_visits_mother_id_idx
    ON pnc_visits (mother_id);

CREATE TABLE IF NOT EXISTS newborn_followups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id BIGINT NOT NULL REFERENCES children(id),
    visit_date DATE NOT NULL,
    feeding_notes VARCHAR(2000),
    clinical_notes VARCHAR(4000),
    referral_notes VARCHAR(2000),
    next_visit_date DATE,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS newborn_followups_child_id_idx
    ON newborn_followups (child_id);

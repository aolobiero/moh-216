CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS children (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_token UUID NOT NULL DEFAULT gen_random_uuid(),
    full_name VARCHAR(150) NOT NULL,
    date_of_birth DATE NOT NULL,
    sex VARCHAR(20) NOT NULL,
    mother_id BIGINT NOT NULL REFERENCES mothers(id),
    birth_weight_kg NUMERIC(5,2),
    birth_facility VARCHAR(150),
    neonatal_history VARCHAR(2000),
    registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT children_birth_weight_positive CHECK (
        birth_weight_kg IS NULL OR birth_weight_kg > 0
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS children_qr_token_unique
    ON children (qr_token);

CREATE INDEX IF NOT EXISTS children_mother_id_idx
    ON children (mother_id);

CREATE INDEX IF NOT EXISTS children_full_name_lower_idx
    ON children (LOWER(full_name));

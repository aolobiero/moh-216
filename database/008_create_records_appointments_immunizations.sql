CREATE TABLE IF NOT EXISTS health_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mother_id BIGINT REFERENCES mothers(id),
    child_id BIGINT REFERENCES children(id),
    record_type VARCHAR(60) NOT NULL,
    title VARCHAR(200) NOT NULL,
    record_date DATE NOT NULL,
    clinical_notes VARCHAR(4000),
    author_username VARCHAR(100) NOT NULL,
    sensitive BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT health_record_subject_check CHECK (
        (mother_id IS NOT NULL AND child_id IS NULL)
        OR (mother_id IS NULL AND child_id IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS health_records_mother_idx ON health_records (mother_id, record_date DESC);
CREATE INDEX IF NOT EXISTS health_records_child_idx ON health_records (child_id, record_date DESC);

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mother_id BIGINT REFERENCES mothers(id),
    child_id BIGINT REFERENCES children(id),
    appointment_type VARCHAR(40) NOT NULL,
    facility_name VARCHAR(200),
    provider_username VARCHAR(100),
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED',
    notes VARCHAR(2000),
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT appointment_subject_check CHECK (
        (mother_id IS NOT NULL AND child_id IS NULL)
        OR (mother_id IS NULL AND child_id IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS appointments_starts_at_idx ON appointments (starts_at);
CREATE INDEX IF NOT EXISTS appointments_status_idx ON appointments (status);

CREATE TABLE IF NOT EXISTS immunization_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id BIGINT NOT NULL REFERENCES children(id),
    vaccine_name VARCHAR(150) NOT NULL,
    dose_label VARCHAR(80),
    administered_date DATE NOT NULL,
    provider_username VARCHAR(100),
    notes VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS immunization_child_idx ON immunization_records (child_id, administered_date DESC);

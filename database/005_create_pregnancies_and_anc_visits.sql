CREATE TABLE IF NOT EXISTS pregnancies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mother_id BIGINT NOT NULL REFERENCES mothers(id),
    last_menstrual_period DATE,
    expected_delivery_date DATE,
    gravida INTEGER CHECK (gravida IS NULL OR gravida >= 0),
    parity INTEGER CHECK (parity IS NULL OR parity >= 0),
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS pregnancies_mother_id_idx
    ON pregnancies (mother_id);

CREATE TABLE IF NOT EXISTS anc_visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregnancy_id BIGINT NOT NULL REFERENCES pregnancies(id),
    visit_date DATE NOT NULL,
    weight_kg NUMERIC(5,2),
    systolic_bp INTEGER,
    diastolic_bp INTEGER,
    clinical_notes VARCHAR(4000),
    follow_up_date DATE,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT anc_weight_positive CHECK (weight_kg IS NULL OR weight_kg > 0),
    CONSTRAINT anc_systolic_positive CHECK (systolic_bp IS NULL OR systolic_bp > 0),
    CONSTRAINT anc_diastolic_positive CHECK (diastolic_bp IS NULL OR diastolic_bp > 0)
);

CREATE INDEX IF NOT EXISTS anc_visits_pregnancy_id_idx
    ON anc_visits (pregnancy_id);
